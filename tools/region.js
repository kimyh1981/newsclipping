// 제목에서 처음 나오는 나라를 찾는다. 섹션 나라가 제목에 있으면 그 나라 이야기로 본다
function regionOf(title, fallback = '') {
  let best = null;
  for (const [name, re] of PLACES) {
    const m = re.exec(title);
    if (!m) continue;
    if (name === fallback) return name;
    if (!best || m.index < best.at) best = { name, at: m.index };
  }
  return best ? best.name : fallback;
}

// 첫머리에 나라 이름을 붙인 읽을 제목. 이미 그 나라 이름으로 시작하면 그대로
function withRegion(spoken, region) {
  if (!region || spoken.startsWith(region)) return spoken;
  return `${region}, ${spoken}`;
}

